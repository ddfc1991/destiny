// 签名配置：CI 里用 keytool 生成 keystore.properties；本地没有则回退到 debug 签名，
// 保证 assembleRelease 永远能产出可安装的 APK。
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}
val hasReleaseKeystore = keystoreProps.getProperty("storeFile") != null &&
    rootProject.file(keystoreProps.getProperty("storeFile", "")).exists()

android {
    namespace = "com.destiny.agent"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.destiny.agent"
        minSdk = 24
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"
        resourceConfigurations += listOf("zh", "en")
    }

    signingConfigs {
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8 混淆/资源压缩：默认开启，体积从 ~10.3MB 降到 ~4MB。
            // 关键前提是 proguard-rules.pro 完整保留了 kotlinx.serialization
            // 的 serializer（反射生成，R8 误裁会导致运行期反序列化崩溃），
            // CI 里有 "Verify R8 kept serializers" 步骤专门盯这条线。
            // 需要回退时用 -Pdestiny.shrink=false。
            val shrink = (project.findProperty("destiny.shrink") as String?)?.toBoolean() ?: true
            isMinifyEnabled = shrink
            isShrinkResources = shrink
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (hasReleaseKeystore) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
        freeCompilerArgs += listOf(
            "-opt-in=androidx.compose.material3.ExperimentalMaterial3Api",
            "-opt-in=androidx.compose.foundation.ExperimentalFoundationApi"
        )
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

